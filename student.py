def grade(overall):
    if overall >= 90:
        print("Student got A grade!")
    elif overall >= 80:
        print("Student got B grade!")
    elif overall >= 70:
        print("Student got C grade!")
    elif overall >= 60:
        print("Student got D grade!")
    elif overall >= 50:
        print("Student got E grade!")
    else:
        print("Student fail!")